"""Run the validation tests and write docs/validation/REPORT.md.

Usage:  python scripts/build_validation_report.py

The report is generated, never hand-written. Cases marked "fonte por verificar"
are listed separately and do not count towards M3.
"""

from __future__ import annotations

import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT)]

import numpy as np  # noqa: E402
import scipy  # noqa: E402
from tests.validation.runner import evaluate, is_runnable, load_cases  # noqa: E402

from georeservoir import __version__  # noqa: E402

OUT = ROOT / "docs" / "validation" / "REPORT.md"
BENCH = ROOT / "docs" / "validation" / "bench.md"


def _git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "n/a (no commit yet)"


def main() -> int:
    pytest_rc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-m", "validation", "-p", "no:cacheprovider"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    cases = load_cases()
    modules = sorted({c["module"] for c in cases})
    lines = [
        "# Validation report (generated)",
        "",
        "Generated by `scripts/build_validation_report.py`. Do not edit by hand.",
        "",
        f"- georeservoir: {__version__}",
        f"- Python: {platform.python_version()} · NumPy: {np.__version__} · "
        f"SciPy: {scipy.__version__}",
        f"- Commit: {_git_commit()}",
        f"- pytest -m validation exit code: {pytest_rc.returncode}",
        "",
        "Kinds: **analytical** = independent closed-form oracle; **spec_conformance** = "
        "hand-checkable evaluation of the published equation (verifies transcription, "
        "not physical validity); **literature** = published case (required for M3).",
        "",
    ]
    pending: list[dict[str, str]] = []
    total = passed = 0
    for mod in modules:
        lines += [
            f"## {mod}",
            "",
            "| Case | Kind | Source | Max abs error | Error / tolerance | Result | Maturity |",
            "|---|---|---|---|---|---|---|",
        ]
        lit_ok: set[str] = set()
        for c in (c for c in cases if c["module"] == mod):
            if not is_runnable(c):
                pending.append(c)
                continue
            r = evaluate(c)
            total += 1
            passed += r["passed"]
            if c["kind"] == "literature" and r["passed"]:
                lit_ok.add(c["function"])
            lines.append(
                f"| {c['id']} | {c['kind']} | {c['source']} | {r['max_abs_error']:.3e} | "
                f"{r['error_to_tolerance']:.3f} | {'PASS' if r['passed'] else 'FAIL'} | "
                f"{r['maturity']} |"
            )
        funcs = sorted({c["function"] for c in cases if c["module"] == mod and is_runnable(c)})
        lines += ["", "| Function | Resulting maturity |", "|---|---|"]
        lines += [
            f"| `{f}` | {'**M3** (literature case reproduced)' if f in lit_ok else 'M2'} |"
            for f in funcs
        ]
        lines.append("")
    lines += [
        "## Fonte por verificar (not counted)",
        "",
        "| Case | Module | Source candidate |",
        "|---|---|---|",
    ]
    lines += [f"| {c['id']} | {c['module']} | {c['source']} |" for c in pending]
    lines += [
        "",
        f"**Summary:** {total + len(pending)} cases · {passed}/{total} runnable cases within "
        f"tolerance · {len(pending)} fonte por verificar.",
        "",
    ]
    if BENCH.exists():
        lines += ["## Performance (from scripts/bench.py)", "", BENCH.read_text().strip(), ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {passed}/{total} passed, {len(pending)} pending")
    return 0 if pytest_rc.returncode == 0 and passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
